        "$projectUnix/src/platform/common/stm32",
        "$projectUnix/lib/main/FatFS",
        "$projectUnix/lib/main/google/nanopb"
    )
    $includesJson = ($includePaths | ForEach-Object { "`"$_`"" }) -join ",`n                "

    $cCcpJson = @"
{
    "configurations": [
        {
            "name": "$TargetMCU",
            "includePath": [
                $($includesJson)
            ],
            "defines": [
                $($definesJson)
