# Betaflight IDE Setup Script
# Usage: .\setup-betaflight.ps1 [-ProjectPath <path>] [-ToolchainPath <path>]
#       .\setup-betaflight.ps1 -ProjectPath "E:\Other\bf" -TargetMCU "STM32F411" -BoardName "CRAZYBEEF4DX"

param(
    [string]$ProjectPath     = $PWD.Path,
    [string]$ToolchainPath   = "D:\tool_chain\arm_gcc_13.1.1",
    [string]$OpenOCDPath     = "D:\OpenOCD-0.12.0",
    [string]$GitBashPath     = "D:\Git\bin\sh.exe",
    [string]$TargetMCU       = "STM32F405",
    [string]$BoardName       = "OMNIBUSF4",
    [int]$AdapterSpeed       = 4000,
    [string]$OpenOCDTargetCfg = "stm32f4x.cfg",
    [switch]$InitSubmodules
)

$ErrorActionPreference = "Stop"

function Write-Step($msg) {
    Write-Host ""
    Write-Host "========================================" -ForegroundColor Cyan
    Write-Host " $msg" -ForegroundColor Cyan
    Write-Host "========================================" -ForegroundColor Cyan
}

function Write-OK($msg)   { Write-Host "  [OK]  $msg" -ForegroundColor Green }
function Write-FAIL($msg) { Write-Host "  [FAIL] $msg" -ForegroundColor Red   }
function Write-INFO($msg) { Write-Host "  [INFO] $msg" -ForegroundColor Yellow }

# Helper: replace backslashes for JSON paths
function To-UnixPath($p) { $p -replace '\\','/' }

function Check-Prereq {
    Write-Step "Check prerequisites"

    $checks = @(
        @{ Name = "Project dir";    Test = { Test-Path $ProjectPath } },
        @{ Name = "Makefile";       Test = { Test-Path "$ProjectPath\Makefile" } },
        @{ Name = "Toolchain root"; Test = { Test-Path $ToolchainPath } },
        @{ Name = "GCC compiler";   Test = { Test-Path "$ToolchainPath\bin\arm-none-eabi-gcc.exe" } },
        @{ Name = "Git Bash";       Test = { Test-Path $GitBashPath } }
    )

    $allOK = $true
    foreach ($c in $checks) {
        if (& $c.Test) { Write-OK $c.Name } else { Write-FAIL $c.Name; $allOK = $false }
    }

    if (Test-Path $OpenOCDPath) {
        if (Test-Path "$OpenOCDPath\bin\openocd.exe") {
            Write-OK "OpenOCD (flash/debug)"
        } else {
            Write-INFO "OpenOCD path exists but openocd.exe not found"
        }
    } else {
        Write-INFO "OpenOCD not found at $OpenOCDPath - flash/debug tasks skipped"
    }

    $gccVersion = & "$ToolchainPath\bin\arm-none-eabi-gcc.exe" --version 2>&1 | Select-Object -First 1
    Write-OK "GCC: $gccVersion"

    if (-not $allOK) {
        throw "Prerequisites check failed"
    }
}

function Setup-Toolchain {
    Write-Step "Setup toolchain (mk/local.mk)"

    $mkDir = Join-Path $ProjectPath "mk"
    if (-not (Test-Path $mkDir)) { New-Item -ItemType Directory -Path $mkDir | Out-Null }

    $localMk = Join-Path $mkDir "local.mk"
    $toolUnix = To-UnixPath $ToolchainPath

    $newContent = @"
# mk/local.mk - Auto-generated by setup-betaflight.ps1
ARM_SDK_PREFIX := $toolUnix/bin/arm-none-eabi-
"@
    [System.IO.File]::WriteAllText($localMk, $newContent, [System.Text.Encoding]::UTF8)
    Write-OK "mk/local.mk written"
}

function Setup-VSCode {
    Write-Step "Setup VS Code IDE"

