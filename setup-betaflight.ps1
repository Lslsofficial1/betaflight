    Write-OK "launch.json"

    # --- settings.json ---
    $toolWinPath = ($ToolchainPath -replace '\\','\\') + "\\bin"
    $settingsJson = @{
        "files.exclude" = @{
            "**/.git" = $true; "**/obj" = $true; "**/downloads" = $true
            "**/tools" = $true; "**/.devcontainer" = $true
        }
        "search.exclude" = @{
            "**/obj" = $true; "**/downloads" = $true; "**/tools" = $true
            "**/.git" = $true; "**/*.o" = $true; "**/*.d" = $true
            "**/*.bin" = $true; "**/*.hex" = $true; "**/*.elf" = $true
            "**/*.dfu" = $true
        }
        "C_Cpp.errorSquiggles" = "enabled"
        "C_Cpp.autocomplete" = "default"
        "editor.formatOnSave" = $false
        "terminal.integrated.env.windows" = @{
            "PATH" = "$toolWinPath;${env:PATH}"
        }
        "git.ignoreMissingGitRepo" = $true
        "cmake.configureOnOpen" = $false
    }
    $settingsPrettified = $settingsJson | ConvertTo-Json -Depth 10
    [System.IO.File]::WriteAllText((Join-Path $vscodeDir "settings.json"), $settingsPrettified, [System.Text.Encoding]::UTF8)
    Write-OK "settings.json"
}

function Setup-GitIgnore {
    Write-Step "Update .gitignore"

    $gitignore = Join-Path $ProjectPath ".gitignore"
    $section = @"

# Betaflight build artifacts
obj/
downloads/
tools/
mk/local.mk
*.hex *.elf *.bin *.dfu
"@

    if (Test-Path $gitignore) {
        $existing = (Get-Content $gitignore -Raw)
        if ($existing -notmatch "Betaflight build artifacts") {
            Add-Content -Path $gitignore -Value $section -Encoding UTF8
            Write-OK ".gitignore updated"
        } else {
            Write-INFO ".gitignore already has betaflight rules"
        }
    } else {
        [System.IO.File]::WriteAllText($gitignore, $section, [System.Text.Encoding]::UTF8)
        Write-OK ".gitignore created"
    }
}

function Run-Submodules {
    if (-not $InitSubmodules) { return }
    Write-Step "Initialize git submodules"
    try {
        Push-Location $ProjectPath
        git submodule update --init --depth 1 --recursive
        Pop-Location
        Write-OK "Submodules initialized"
    } catch {
        Write-FAIL "Submodule init failed: $_"
        Write-INFO "Run manually: git submodule update --init --recursive"
    }
}

function Print-Summary {
    Write-Step "Setup complete"

    $openocdOk = Test-Path "$OpenOCDPath\bin\openocd.exe"
    $gccVersion = & "$ToolchainPath\bin\arm-none-eabi-gcc.exe" --version 2>&1 | Select-Object -First 1
    $boardElf = if ($BoardName -eq $TargetMCU) {
        "betaflight_${TargetMCU}.elf"
    } else {
        "betaflight_${TargetMCU}_${BoardName}.elf"
    }

    Write-Host ""
    Write-Host "  Project  : $ProjectPath"
    Write-Host "  GCC      : $gccVersion"
    Write-Host "  OpenOCD  : $(if ($openocdOk) { "$OpenOCDPath (ready)" } else { "not installed" })"
    Write-Host "  Target   : $TargetMCU ($BoardName)"
    Write-Host "  ELF      : obj/main/$boardElf"
    Write-Host ""
    Write-Host "  VS Code tasks:"
    Write-Host "    Ctrl+Shift+B       ->  make $TargetMCU"
    Write-Host "    Ctrl+Shift+P       ->  Tasks: Run Task"
    Write-Host "      -> make $TargetMCU"
    Write-Host "      -> make $BoardName"
    if ($openocdOk) {
        Write-Host "      -> openocd-flash $TargetMCU"
        Write-Host "      -> openocd-erase $TargetMCU"
    }
    Write-Host ""
    Write-Host "  Debug (F5):  Select 'DAPLink OpenOCD - $TargetMCU'"
}

